#!/usr/bin/env python3
"""Writes FLAGS.md: every -Dmcopt.* flag the code reads, what the default (indie) profile sets it to, and where it's read.

Run from anywhere: python3 tools/flags.py. Flags are found as string literals ("mcopt.x.y") plus the prefix lookups that build
names at runtime ("mcopt.chunk." + name with prop("name"), "mcopt.qos." + role over a String[], OwnFrag's flag-name array).
A flag is marked measurement-only when the comment next to where it's read says so.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "metal/src/main/java"
PROFILES = ROOT / "metal/src/main/resources/mcopt/profiles"
OUT = ROOT / "FLAGS.md"

LITERAL = re.compile(r'"(mcopt\.[a-z][A-Za-z0-9_.]*[A-Za-z0-9_])"')
NOT_FLAGS = {"mcopt.properties"}  # the config file's name, not a switch
PREFIX = re.compile(r'"(mcopt\.[A-Za-z0-9_.]+\.)"\s*\+')
PROP_CALL = re.compile(r'\bprop\("([A-Za-z0-9_]+)"\)')
ARRAY = re.compile(r'new String\[\]\s*\{([^}]*)\}')
STRING = re.compile(r'"([A-Za-z0-9_]+)"')
MEASURE = re.compile(r'measurement( only)?|\(measurement|A/B runs|for A/B', re.I)


def profile(name):
    keys = {}
    for line in (PROFILES / f"{name}.properties").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            keys[k.strip()] = v.strip()
    return keys


def scan():
    flags = {}  # name -> {"files": set, "measure": bool}

    def add(name, rel, context):
        f = flags.setdefault(name, {"files": set(), "measure": False})
        f["files"].add(rel)
        if MEASURE.search(context):
            f["measure"] = True

    for path in sorted(SRC.rglob("*.java")):
        rel = path.relative_to(SRC).as_posix().removeprefix("mcopt/metal/").removesuffix(".java")
        lines = path.read_text().splitlines()
        text = "\n".join(lines)
        for i, line in enumerate(lines):
            context = "\n".join(lines[max(0, i - 3):i + 1])
            for m in LITERAL.finditer(line):
                if m.group(1) in NOT_FLAGS:
                    continue
                add(m.group(1), rel, context)
            for m in PREFIX.finditer(line):
                prefix = m.group(1)
                names = set()
                for arr in ARRAY.finditer("\n".join(lines[max(0, i - 2):i + 1])):
                    names.update(STRING.findall(arr.group(1)))
                if not names:  # a helper like prop(name): every prop("x") in the file
                    names.update(PROP_CALL.findall(text))
                for n in names:
                    add(prefix + n, rel, context)
    return flags


def main():
    flags = scan()
    indie = profile("indie")
    unknown = sorted(k for k in indie if k not in flags)
    groups = {}
    for name in flags:
        groups.setdefault(".".join(name.split(".")[:2]), []).append(name)

    out = ["# mcopt flags", "",
           "Generated by `tools/flags.py`; don't edit by hand. Every `-Dmcopt.*` switch the code reads. A switch can also go in",
           "`config/mcopt.properties`, and the command line wins over that file, which wins over the profile.", "",
           f"{len(flags)} flags; {len(indie)} set by the default `indie` profile; "
           f"{sum(f['measure'] for f in flags.values())} marked measurement-only.", ""]
    if unknown:
        out += ["**The indie profile sets keys no code reads:** " + ", ".join(f"`{k}`" for k in unknown), ""]
    for group in sorted(groups):
        out += [f"## {group}", "", "| flag | indie | measurement | read in |", "|---|---|---|---|"]
        for name in sorted(groups[group]):
            f = flags[name]
            out.append(f"| `{name}` | {('`' + indie[name] + '`') if name in indie else ''} | {'yes' if f['measure'] else ''} | "
                       + ", ".join(sorted(f["files"])) + " |")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(flags)} flags, {len(unknown)} profile keys unread", file=sys.stderr)


if __name__ == "__main__":
    main()
